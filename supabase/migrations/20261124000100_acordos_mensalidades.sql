-- Sistema Guarani: estrutura inicial para acordos de mensalidades.
-- Esta migration cria somente a estrutura; não altera mensalidades históricas.
-- Executar no Supabase somente após revisar a implementação correspondente.

CREATE TABLE IF NOT EXISTS public.acordos_mensalidades (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  socio_id uuid NOT NULL REFERENCES public.socios(id) ON DELETE RESTRICT,
  numero bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
  data_acordo date NOT NULL DEFAULT (timezone('America/Sao_Paulo', now())::date),
  valor_total numeric(12,2) NOT NULL CHECK (valor_total > 0),
  valor_entrada numeric(12,2) NOT NULL DEFAULT 0 CHECK (valor_entrada >= 0),
  quantidade_parcelas integer NOT NULL CHECK (quantidade_parcelas >= 0),
  observacoes text,
  situacao text NOT NULL DEFAULT 'ativo'
    CHECK (situacao IN ('ativo', 'concluido', 'cancelado')),
  created_by uuid,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT acordos_entrada_nao_supera_total CHECK (valor_entrada <= valor_total)
);

CREATE TABLE IF NOT EXISTS public.acordos_mensalidades_itens (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  acordo_id uuid NOT NULL REFERENCES public.acordos_mensalidades(id) ON DELETE RESTRICT,
  mensalidade_id uuid NOT NULL REFERENCES public.mensalidades(id) ON DELETE RESTRICT,
  valor_original numeric(12,2) NOT NULL CHECK (valor_original >= 0),
  ativo boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS acordo_mensalidade_unica_ativa_idx
  ON public.acordos_mensalidades_itens (mensalidade_id)
  WHERE ativo = true;

CREATE TABLE IF NOT EXISTS public.acordos_mensalidades_parcelas (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  acordo_id uuid NOT NULL REFERENCES public.acordos_mensalidades(id) ON DELETE RESTRICT,
  numero integer NOT NULL CHECK (numero > 0),
  descricao text,
  valor numeric(12,2) NOT NULL CHECK (valor > 0),
  data_vencimento date NOT NULL,
  situacao text NOT NULL DEFAULT 'em_aberto'
    CHECK (situacao IN ('em_aberto', 'pago', 'em_compensacao', 'cancelado')),
  data_pagamento date,
  forma_pagamento text
    CHECK (forma_pagamento IS NULL OR forma_pagamento IN
      ('pix', 'debito_em_conta', 'boleto', 'dinheiro', 'transferencia', 'cartao', 'outro')),
  conta_bancaria_id uuid REFERENCES public.contas_bancarias(id) ON DELETE RESTRICT,
  movimentacao_id uuid REFERENCES public.movimentacoes_financeiras(id) ON DELETE RESTRICT,
  comprovante_url text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT acordo_parcela_numero_unico UNIQUE (acordo_id, numero),
  CONSTRAINT acordo_parcela_pagamento_consistente CHECK (
    (situacao <> 'pago' OR (data_pagamento IS NOT NULL AND forma_pagamento IS NOT NULL))
  )
);

CREATE INDEX IF NOT EXISTS acordos_mensalidades_socio_idx
  ON public.acordos_mensalidades (socio_id, data_acordo DESC);
CREATE INDEX IF NOT EXISTS acordos_mensalidades_situacao_idx
  ON public.acordos_mensalidades (situacao);
CREATE INDEX IF NOT EXISTS acordos_mensalidades_itens_acordo_idx
  ON public.acordos_mensalidades_itens (acordo_id);
CREATE INDEX IF NOT EXISTS acordos_mensalidades_parcelas_vencimento_idx
  ON public.acordos_mensalidades_parcelas (data_vencimento, situacao);
CREATE INDEX IF NOT EXISTS acordos_mensalidades_parcelas_acordo_idx
  ON public.acordos_mensalidades_parcelas (acordo_id, numero);

-- Acesso apenas pelo backend com service_role. Não expor as tabelas diretamente
-- aos clientes autenticados; as rotas administrativas validam o perfil.
ALTER TABLE public.acordos_mensalidades ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.acordos_mensalidades_itens ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.acordos_mensalidades_parcelas ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE public.acordos_mensalidades FROM anon, authenticated;
REVOKE ALL ON TABLE public.acordos_mensalidades_itens FROM anon, authenticated;
REVOKE ALL ON TABLE public.acordos_mensalidades_parcelas FROM anon, authenticated;
GRANT ALL ON TABLE public.acordos_mensalidades TO service_role;
GRANT ALL ON TABLE public.acordos_mensalidades_itens TO service_role;
GRANT ALL ON TABLE public.acordos_mensalidades_parcelas TO service_role;

COMMENT ON TABLE public.acordos_mensalidades IS
  'Acordos administrativos para renegociação de mensalidades vencidas.';
COMMENT ON TABLE public.acordos_mensalidades_itens IS
  'Vínculo auditável entre mensalidades originais e acordos; não altera o histórico da mensalidade.';
COMMENT ON TABLE public.acordos_mensalidades_parcelas IS
  'Parcelas a receber dos acordos, integradas ao financeiro por movimentacao_id.';
